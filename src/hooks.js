/**
 * M.H. AI Sync - Native Git Hooks Engine
 * Installs and manages zero-dependency native Git hooks to enforce AI synchronization
 * and security scanning before code is committed locally.
 */

const fs = require('fs');
const path = require('path');

function getGitHooksDir(rootDir = process.cwd()) {
  const gitPath = path.join(rootDir, '.git');
  if (!fs.existsSync(gitPath)) {
    return null;
  }

  try {
    const stat = fs.statSync(gitPath);
    if (stat.isDirectory()) {
      return path.join(gitPath, 'hooks');
    }
    if (stat.isFile()) {
      // Handle git worktree or git submodule pointer
      const content = fs.readFileSync(gitPath, 'utf8').trim();
      if (content.startsWith('gitdir:')) {
        let actualGitDir = content.slice(7).trim();
        if (!path.isAbsolute(actualGitDir)) {
          actualGitDir = path.resolve(rootDir, actualGitDir);
        }
        return path.join(actualGitDir, 'hooks');
      }
    }
  } catch {}

  return null;
}

function generatePreCommitScript() {
  return `#!/bin/sh
# M.H. AI Sync - Pre-commit Hook
# Auto-generated by M.H. AI Sync (https://github.com/mhnadali/mh-ai-sync)

echo ""
echo "\\033[1m\\033[36m[M.H. AI Sync]\\033[0m Running pre-commit AI context & security verification..."

# 1. Security Scan (Block on leaked API keys, tokens, or private credentials)
if [ -f "./bin/index.js" ]; then
  node bin/index.js audit --strict
else
  npx --no-install mh-ai-sync audit --strict
fi
AUDIT_EXIT=$?
if [ $AUDIT_EXIT -ne 0 ]; then
  echo ""
  echo "\\033[31m✖ [M.H. AI Sync Error] Commit rejected: Sensitive credentials or API keys found!\\033[0m"
  echo "\\033[33m  Hint: Run 'mhai audit' to view findings or 'mhai build --redact' to auto-sanitize.\\033[0m"
  echo ""
  exit 1
fi

# 2. Synchronization Drift Check (Block on modified or un-synced AI instructions)
if [ -f "./bin/index.js" ]; then
  node bin/index.js status --check
else
  npx --no-install mh-ai-sync status --check
fi
STATUS_EXIT=$?
if [ $STATUS_EXIT -ne 0 ]; then
  echo ""
  echo "\\033[31m✖ [M.H. AI Sync Error] Commit rejected: AI agent context drift detected!\\033[0m"
  echo "\\033[33m  Hint: Run 'mhai build' or 'mhai merge' to align agent configurations before committing.\\033[0m"
  echo ""
  exit 1
fi

echo "\\033[32m✔ [M.H. AI Sync] All pre-commit AI guardrails passed!\\033[0m"
echo ""
exit 0
`;
}

function installHook(rootDir = process.cwd()) {
  const hooksDir = getGitHooksDir(rootDir);
  if (!hooksDir) {
    throw new Error('Not a git repository: .git directory not found.');
  }

  if (!fs.existsSync(hooksDir)) {
    fs.mkdirSync(hooksDir, { recursive: true });
  }

  const hookPath = path.join(hooksDir, 'pre-commit');
  fs.writeFileSync(hookPath, generatePreCommitScript(), { encoding: 'utf8', mode: 0o755 });

  try {
    fs.chmodSync(hookPath, 0o755);
  } catch {
    // Windows chmod fallback safe
  }

  return {
    success: true,
    hookPath,
    relativePath: path.join('.git', 'hooks', 'pre-commit')
  };
}

function uninstallHook(rootDir = process.cwd()) {
  const hooksDir = getGitHooksDir(rootDir);
  if (!hooksDir) {
    throw new Error('Not a git repository: .git directory not found.');
  }

  const hookPath = path.join(hooksDir, 'pre-commit');
  if (fs.existsSync(hookPath)) {
    const content = fs.readFileSync(hookPath, 'utf8');
    if (content.includes('M.H. AI Sync')) {
      fs.unlinkSync(hookPath);
      return { success: true, removed: true };
    } else {
      return { success: false, removed: false, reason: 'Hook was not created by M.H. AI Sync' };
    }
  }

  return { success: true, removed: false, reason: 'No pre-commit hook existed' };
}

function isHookInstalled(rootDir = process.cwd()) {
  const hooksDir = getGitHooksDir(rootDir);
  if (!hooksDir) return false;
  const hookPath = path.join(hooksDir, 'pre-commit');
  if (!fs.existsSync(hookPath)) return false;
  const content = fs.readFileSync(hookPath, 'utf8');
  return content.includes('M.H. AI Sync');
}

module.exports = {
  installHook,
  uninstallHook,
  isHookInstalled,
  getGitHooksDir,
  generatePreCommitScript
};
